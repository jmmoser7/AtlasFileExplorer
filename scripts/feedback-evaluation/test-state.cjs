// These checks guard evidence semantics, not native Slate behavior.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const catalog = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../docs/requests/2026-10-16/slate-acceptance.cases.json'), 'utf8'));
catalog.catalogHash = 'state-regression';
const source = fs.readFileSync(path.join(__dirname, 'app.js'), 'utf8');
const core = source.slice(0, source.indexOf("$('run-form').addEventListener('submit'"));
assert.ok(core.length > 5000, 'Find the actual state functions before UI event wiring');
const browserWindow = {}; browserWindow.parent = browserWindow;
const context = {assert, crypto, window: browserWindow, document: {getElementById: () => ({textContent: JSON.stringify(catalog)})}, localStorage: {getItem: () => null}};
vm.runInNewContext(core + `
const sample = DATA.cases[0];
const run = freshRun();
assert.equal(verdict(sample, run), 'untested');
run.results[sample.id] = {checks: Object.fromEntries(sample.checks.map(c => [c.id, {status:'pass'}])), notes:'', evidence:''};
assert.equal(verdict(sample, run), 'partial', 'No evidence or context cannot pass');
run.locked = true;
Object.assign(run.meta, {tester:'Test evaluator', identity:'Exact binary hash', binary:'fixture/slate.exe', context:'Fixture workbook', confirmed:true});
assert.equal(verdict(sample, run), 'partial', 'All green checkboxes still need evidence');
run.results[sample.id].notes = 'Observed every clause in the named fixture';
assert.equal(verdict(sample, run), 'pass');
run.results[sample.id].checks[sample.checks[0].id].status = 'blocked';
assert.equal(verdict(sample, run), 'blocked', 'Missing prerequisite cannot pass');
if (sample.checks.length > 1) run.results[sample.id].checks[sample.checks[1].id].status = 'fail';
assert.equal(verdict(sample, run), 'fail', 'A failed clause outranks blocked/passed clauses');
for (const c of sample.checks) run.results[sample.id].checks[c.id].status = 'pass';
const previous = {runs:[run], active:run.id, handoff:'older-binary-sha'};
const rollover = validateStore(previous);
assert.equal(rollover.runs.length, 2, 'New build retains previous evidence');
assert.notEqual(rollover.active, run.id, 'New build cannot select an old passing run');
assert.equal(verdict(sample, rollover.runs[0]), 'untested');
assert.equal(verdict(sample, rollover.runs[1]), 'pass', 'Historical evidence retains its own context');
assert.equal(validateStore(rollover).runs.length, 2, 'Reload does not invent more new runs');
const clean = freshRun();
assert.equal(Object.keys(clean.results).length, 0);
assert.equal(clean.meta.confirmed, false);
const report = sample.reports[0];
const linked = DATA.cases.filter(c => c.reports.includes(report));
assert.ok(linked.length > 1, 'Use a report with several independently evaluated cases');
assert.equal(reportVerdicts(run).find(r => r.id === report).status, 'partial', 'One passing case cannot resolve a multi-case report');
assert.throws(() => validateStore({runs:[run,run]}), /Duplicate/);
assert.throws(() => validateRun({id:'invalid', results:{}}), /Invalid/);
const unconfirmed = validateRun({...run, meta:{...run.meta, confirmed:false}});
assert.equal(verdict(sample, unconfirmed), 'partial', 'Imported unchecked context cannot produce a pass');
`, context);
console.log('Acceptance-state checks passed: clause precedence, evidence, full-report coverage, fresh build/run, history, import validation.');
