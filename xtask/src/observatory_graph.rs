//! Export the code-lens source graph independently of history/metrics refresh.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::path::Path;

use code_lens::model::NodeKind;
use serde::Serialize;

use crate::collect::workspace_members;
use crate::observatory::{declared_edges, dependency_closure};

#[derive(Serialize)]
struct Node {
    id: String,
    parent: Option<String>,
    kind: &'static str,
    name: String,
    path: String,
    line: u32,
    #[serde(rename = "endLine")]
    end_line: u32,
    loc: u32,
    #[serde(rename = "selfLoc")]
    self_loc: u32,
    #[serde(rename = "crate")]
    package: Option<String>,
    #[serde(skip_serializing_if = "String::is_empty")]
    doc: String,
    conditional: bool,
}

#[derive(Serialize)]
struct Edge {
    from: String,
    to: String,
    kind: &'static str,
    weight: u32,
}

pub fn write(root: &Path) -> Result<(), Box<dyn std::error::Error>> {
    crate::verify_workspace_root(root)?;
    let destination = root.join("tools/slate-observatory/code-graph.js");
    std::fs::create_dir_all(destination.parent().unwrap())?;
    let result = collect(root);
    let payload = match &result {
        Ok(payload) => payload.clone(),
        Err(error) => {
            serde_json::json!({ "available": false, "error": error.to_string().replace(root.to_string_lossy().as_ref(), "<workspace>"), "nodes": [], "edges": [] })
        }
    };
    std::fs::write(destination, format!("// Generated by cargo xtask observatory-graph. Static source extraction.\nwindow.SLATE_CODE_GRAPH = {};\n", serde_json::to_string(&payload)?))?;
    result.map(|_| ())
}

fn collect(root: &Path) -> Result<serde_json::Value, Box<dyn std::error::Error>> {
    let members = workspace_members(root)?;
    if !members.iter().any(|m| m.name == "slate") {
        return Err("No Slate workspace member".into());
    }
    let dependencies = declared_edges(&members);
    let scope = dependency_closure("slate", &dependencies);
    let selected = scope.iter().cloned().collect::<Vec<_>>();
    let analysis = code_lens::observatory::analyze_observatory(root, &selected)
        .map_err(|error| std::io::Error::other(format!("{error:?}")))?;
    let mut ids = Vec::new();
    let mut seen = BTreeSet::new();
    for info in &analysis.source {
        let id = code_lens::observatory::stable_id(&info.identity);
        if !seen.insert(id.clone()) {
            return Err("Duplicate source identity or ID hash collision".into());
        }
        ids.push(id);
    }
    let mut package_nodes = HashMap::new();
    for node in &analysis.graph.nodes {
        if matches!(node.kind, NodeKind::Package { .. }) {
            package_nodes.insert(node.name.clone(), node.id);
        }
    }
    let nodes: Vec<_> = analysis
        .graph
        .nodes
        .iter()
        .map(|node| {
            let info = &analysis.source[node.id as usize];
            let mut cursor = Some(node.id);
            let mut package = None;
            while let Some(id) = cursor {
                let ancestor = analysis.graph.node(id);
                if matches!(ancestor.kind, NodeKind::Package { .. }) {
                    package = Some(ancestor.name.clone());
                    break;
                }
                cursor = ancestor.parent;
            }
            Node {
                id: ids[node.id as usize].clone(),
                parent: node.parent.map(|p| ids[p as usize].clone()),
                kind: info.kind,
                name: node.name.clone(),
                path: node.path.to_string_lossy().replace('\\', "/"),
                line: info.line,
                end_line: info.end_line,
                loc: node.loc,
                self_loc: info.self_loc,
                package,
                doc: info.doc.clone(),
                conditional: info.conditional,
            }
        })
        .collect();
    let mut edges = Vec::new();
    for edge in dependencies
        .iter()
        .filter(|e| scope.contains(&e.source) && scope.contains(&e.target))
    {
        edges.push(Edge {
            from: ids[package_nodes[&edge.source] as usize].clone(),
            to: ids[package_nodes[&edge.target] as usize].clone(),
            kind: "dependency",
            weight: 1,
        });
    }
    for edge in &analysis.relations {
        edges.push(Edge {
            from: ids[edge.from as usize].clone(),
            to: ids[edge.to as usize].clone(),
            kind: edge.kind,
            weight: edge.weight,
        });
    }
    let mut kinds = BTreeMap::new();
    for node in &nodes {
        *kinds.entry(node.kind).or_insert(0_usize) += 1;
    }
    Ok(serde_json::json!({
        "available": true, "partial": !analysis.failures.is_empty(), "generatedAt": analysis.graph.generated_at,
        "root": ids[analysis.graph.root as usize], "nodes": nodes, "edges": edges,
        "counts": { "nodes": analysis.graph.nodes.len(), "edges": edges.len(), "kinds": kinds, "extraction": analysis.counts },
        "failures": analysis.failures,
        "definitions": {
            "scope": "Today's Slate dependency closure, including physical Rust src/ and tests/ files. Third-party source, examples, build.rs and excluded workspace crates are omitted.",
            "loc": "Full physical source lines. File totals are counted once in directory/crate/workspace totals. Symbols use inclusive physical spans. Child areas normalize locally; sibling spans can share a line. selfLoc is the remaining parent span outside the union of immediate-child spans.",
            "symbols": "Named syn-parsed Rust items, inline/out-of-line module declarations, nested functions, inherent/trait methods and associated types/constants. Macro-generated items and closures are not expanded into named function nodes. All cfg branches are present; conditional records direct/inherited cfg attributes within a file.",
            "dependency": "Canonical local Cargo declarations, including target-specific, dev, build and optional dependencies. This is not a resolved build graph.",
            "module": "Explicit out-of-line mod declaration to its proven source file. Conventional roots and literal top-level #[path] declarations are supported; unsupported or ambiguous routes remain unresolved.",
            "import": "An explicit use path resolved to one unique source declaration or proven module. Aliases are honored. Symbol bindings through globs are supported only for proven ancestor super::* / crate::* namespaces; sibling/external/unknown globs remain unresolved.",
            "implements": "An explicit impl Trait path resolved to one exact trait declaration. No global same-name fallback.",
            "call": "Observed syntactic call site resolving to one lexical/qualified function or proven inherent self method. Shadowed values, ambiguous cfg declarations, generic self types, indirect/dynamic receivers, trait dispatch and unknown external targets remain unresolved. Calls inside closures belong to their lexical item. This is not a compiler-complete call graph or runtime trace.",
            "identities": "Stable FNV-1a IDs from repository-relative source identity, symbol ancestry, kind and duplicate ordinal. Line-only shifts do not change IDs. Renames/moves and duplicate declaration reordering can change identity; collisions fail generation.",
            "errors": "Read/extraction errors fail generation explicitly. Individual Rust parse failures retain file area but have no fabricated symbol nodes; listed failures set partial=true. Unresolved relation counts measure observed syntax only, not missing macro/dynamic call coverage."
        }
    }))
}
